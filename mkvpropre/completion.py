"""Shell completion scripts (bash, zsh, fish), generated from the argparse parser.

No dependency: the scripts are static text printed by `mkvpropre --completion
SHELL`, so pressing Tab never runs Python. They follow the parser, so a new
option is completed as soon as it exists.

What is completed, per option:
- flags: nothing after them;
- `choices`: those words;
- an `action.completion` attribute set in cli.py: "dirs" (folders only) or a
  word list (suggestions, any value still accepted);
- other options taking a value: nothing (free text);
- positional arguments: .mkv files and folders.
"""
from __future__ import annotations

import argparse
import sys
from dataclasses import dataclass

SHELLS = ("bash", "zsh", "fish")
DIRS = "dirs"


@dataclass(frozen=True)
class Option:
    shorts: tuple[str, ...]          # "-V"
    longs: tuple[str, ...]           # "--version"
    help: str
    takes_value: bool
    words: tuple[str, ...] = ()      # values to offer
    dirs: bool = False               # folders only

    @property
    def strings(self) -> tuple[str, ...]:
        return self.shorts + self.longs


def short_help(parser: argparse.ArgumentParser, action: argparse.Action) -> str:
    """The help text with %(default)s expanded, first clause only, on one line."""
    if not action.help or action.help == argparse.SUPPRESS:
        return ""
    text = argparse.HelpFormatter(parser.prog)._expand_help(action)
    text = " ".join(text.split())
    for sep in ("; ", " (default"):            # keep the example of "--show", drop the details
        text = text.split(sep)[0]
    return text if len(text) <= 70 else text[:67].rstrip() + "..."


def options(parser: argparse.ArgumentParser) -> list[Option]:
    result = []
    for action in parser._actions:
        if not action.option_strings or action.help == argparse.SUPPRESS:
            continue
        takes_value = action.nargs != 0
        hint = getattr(action, "completion", None)
        words: tuple[str, ...] = ()
        if action.choices:
            words = tuple(str(c) for c in action.choices)
        elif isinstance(hint, (list, tuple)):
            words = tuple(hint)
        result.append(Option(
            shorts=tuple(s for s in action.option_strings if not s.startswith("--")),
            longs=tuple(s for s in action.option_strings if s.startswith("--")),
            help=short_help(parser, action),
            takes_value=takes_value,
            words=words,
            dirs=hint == DIRS,
        ))
    return result


def generate(parser: argparse.ArgumentParser, shell: str) -> str:
    prog = parser.prog
    opts = options(parser)
    if shell == "bash":
        return bash(prog, opts)
    if shell == "zsh":
        return zsh(prog, opts)
    if shell == "fish":
        return fish(prog, opts)
    raise ValueError(f"unsupported shell {shell!r}, use one of {', '.join(SHELLS)}")


def _func(prog: str) -> str:
    return "_" + "".join(c if c.isalnum() else "_" for c in prog)


# --- bash -------------------------------------------------------------------------------------

def bash(prog: str, opts: list[Option]) -> str:
    func = _func(prog)
    cases = []
    for o in opts:
        if not o.takes_value:
            continue
        pattern = "|".join(o.strings)
        if o.dirs:
            body = 'local IFS=$\'\\n\'; COMPREPLY=($(compgen -d -- "$cur"))'
        elif o.words:
            body = (f'{func}_words; COMPREPLY=($(compgen -W "{" ".join(o.words)}" -- "$cur"))')
        else:
            body = f"{func}_words; COMPREPLY=()"
        cases.append(f"        {pattern})\n            {body}\n            ;;")
    all_opts = " ".join(s for o in opts for s in o.strings)
    return f"""# bash completion for {prog}, generated by `{prog} --completion bash`

# Plain words, not file names: don't escape them ("TheMovieDB::TV", not "TheMovieDB\\:\\:TV").
{func}_words() {{
    type compopt &>/dev/null && compopt +o filenames
}}

{func}() {{
    local cur prev colon=""
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    # bash splits "TheMovieDB::TV" on ":" (COMP_WORDBREAKS): when the word being typed
    # contains one, take it and its option from the line as typed instead.
    local before="${{COMP_LINE:0:COMP_POINT}}" typed=()
    if [[ "${{before##*[[:space:]]}}" == *:* ]]; then
        read -ra typed <<< "$before"
        cur="${{typed[${{#typed[@]}}-1]}}"
        prev="${{typed[${{#typed[@]}}-2]}}"
        colon="${{cur%"${{cur##*:}}"}}"              # "TheMovieDB::", already on the line for bash
    fi
    case "$prev" in
{chr(10).join(cases)}
        *)
            if [[ "$cur" == -* ]]; then
                {func}_words
                COMPREPLY=($(compgen -W "{all_opts}" -- "$cur"))
            else
                # .mkv files and folders (one per line: names may contain spaces)
                local IFS=$'\\n'
                COMPREPLY=($(compgen -f -X '!*.[mM][kK][vV]' -- "$cur") $(compgen -d -- "$cur"))
            fi
            ;;
    esac
    if [[ -n "$colon" ]]; then
        COMPREPLY=("${{COMPREPLY[@]#"$colon"}}")
    fi
    return 0
}}
complete -o filenames -F {func} {prog}
"""


# --- zsh ---------------------------------------------------------------------------------------

def _zsh_escape(text: str) -> str:
    """For a description inside '...[here]...' in an _arguments spec."""
    text = text.replace("\\", "\\\\").replace("[", "\\[").replace("]", "\\]").replace(":", "\\:")
    return text.replace("'", "'\\''")


def zsh(prog: str, opts: list[Option]) -> str:
    func = _func(prog)
    specs = []
    for o in opts:
        desc = _zsh_escape(o.help)
        action = ""
        if o.takes_value:
            if o.dirs:
                action = ":directory:_files -/"
            elif o.words:
                action = ":value:(" + " ".join(w.replace(":", "\\:") for w in o.words) + ")"
            else:
                action = ":value: "
        if len(o.strings) > 1:
            excl = " ".join(o.strings)
            names = "{" + ",".join(o.strings) + "}"
            specs.append(f"'({excl})'{names}'[{desc}]{action}'")
        else:
            specs.append(f"'{o.strings[0]}[{desc}]{action}'")
    specs.append("'*:file or folder:_files -g \"*.(#i)mkv(-.)\"'")
    lines = " \\\n    ".join(specs)
    return f"""#compdef {prog}
# zsh completion for {prog}, generated by `{prog} --completion zsh`
{func}() {{
  _arguments -s -S \\
    {lines}
}}

if [ "$funcstack[1]" = "{func}" ]; then
  {func} "$@"
else
  compdef {func} {prog}
fi
"""


# --- fish --------------------------------------------------------------------------------------

def _fish_quote(text: str) -> str:
    return "'" + text.replace("\\", "\\\\").replace("'", "\\'") + "'"


def fish(prog: str, opts: list[Option]) -> str:
    lines = [f"# fish completion for {prog}, generated by `{prog} --completion fish`"]
    for o in opts:
        parts = [f"complete -c {prog}"]
        parts += [f"-s {s.lstrip('-')}" for s in o.shorts]
        parts += [f"-l {s[2:]}" for s in o.longs]
        if o.takes_value:
            if o.dirs:
                parts.append("-x -a '(__fish_complete_directories)'")
            elif o.words:
                parts.append("-x -a " + _fish_quote(" ".join(o.words)))
            else:
                parts.append("-x")
        if o.help:
            parts.append("-d " + _fish_quote(o.help))
        lines.append(" ".join(parts))
    return "\n".join(lines) + "\n"


class CompletionAction(argparse.Action):
    """`--completion SHELL`: print the script and exit, like --version."""

    def __init__(self, option_strings, dest, **kwargs):
        kwargs.setdefault("choices", SHELLS)
        kwargs.setdefault("metavar", "{" + ",".join(SHELLS) + "}")
        super().__init__(option_strings, dest, **kwargs)

    def __call__(self, parser, namespace, values, option_string=None):
        sys.stdout.write(generate(parser, values))
        parser.exit()
